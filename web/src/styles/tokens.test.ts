import { execFileSync, spawnSync } from "node:child_process";
import { copyFile, mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { describe, expect, it } from "vitest";

type OklchColor = {
  $type: "color";
  $value: {
    alpha: number;
    colorSpace: "oklch";
    components: [number, number, number];
  };
};

type TokenDocument = {
  color: {
    light: Record<string, OklchColor>;
    dark: Record<string, OklchColor>;
  };
};

const repoRoot = resolve(process.cwd(), "..");
const tokenPath = resolve(repoRoot, "web/src/styles/tokens.json");
const contrastScript = resolve(repoRoot, "scripts/contrast.py");

async function readTokens(): Promise<TokenDocument> {
  return JSON.parse(await readFile(tokenPath, "utf8")) as TokenDocument;
}

function requiredColor(colors: Record<string, OklchColor>, name: string): OklchColor {
  const color = colors[name];
  if (!color) {
    throw new Error(`Missing color token ${name}`);
  }
  return color;
}

async function runContrastFixture(tokens: TokenDocument) {
  const directory = await mkdtemp(join(tmpdir(), "kinevo-contrast-"));
  const scriptDirectory = join(directory, "scripts");
  const tokenDirectory = join(directory, "web/src/styles");
  await mkdir(scriptDirectory, { recursive: true });
  await mkdir(tokenDirectory, { recursive: true });
  await copyFile(contrastScript, join(scriptDirectory, "contrast.py"));
  await writeFile(join(tokenDirectory, "tokens.json"), JSON.stringify(tokens));

  try {
    return spawnSync("python3", [join(scriptDirectory, "contrast.py"), "--markdown"], {
      cwd: directory,
      encoding: "utf8",
    });
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
}

describe("tokens", () => {
  it("tst_10_contrast_gate_reads_json", async () => {
    const generated = spawnSync("python3", [contrastScript, "--markdown"], {
      cwd: repoRoot,
      encoding: "utf8",
    });
    expect(generated.status).toBe(0);

    const specification = await readFile(resolve(repoRoot, "spec/09-design-system.md"), "utf8");
    const marker =
      "<!-- generated by `python3 scripts/contrast.py --markdown`; do not edit by hand -->";
    const sectionStart = specification.indexOf(marker) + marker.length;
    const sectionEnd = specification.indexOf("\n### Semantic usage", sectionStart);
    expect(sectionStart).toBeGreaterThan(marker.length);
    expect(sectionEnd).toBeGreaterThan(sectionStart);
    expect(generated.stdout.trim()).toBe(specification.slice(sectionStart, sectionEnd).trim());

    const tokens = await readTokens();
    const changed = structuredClone(tokens);
    requiredColor(changed.color.light, "paper").$value.components[0] = 0.96;
    const changedRun = await runContrastFixture(changed);
    expect(changedRun.status).toBe(0);
    expect(changedRun.stdout).toContain("oklch(0.96 0.012 85)");
    expect(changedRun.stdout).not.toBe(generated.stdout);
  });

  it("contrast_failure_is_reported", async () => {
    const tokens = await readTokens();
    const changed = structuredClone(tokens);
    const paper = requiredColor(changed.color.light, "paper");
    const accent = requiredColor(changed.color.light, "accent");
    accent.$value.components = [...paper.$value.components] as [number, number, number];

    const result = await runContrastFixture(changed);
    expect(result.status).toBe(1);
    expect(`${result.stdout}\n${result.stderr}`).toContain("accent");
    expect(`${result.stdout}\n${result.stderr}`).toContain("paper");
  });

  it("generated_css_matches_committed", async () => {
    const stylesDirectory = resolve(repoRoot, "web/src/styles");
    const committedCss = await readFile(join(stylesDirectory, "tokens.css"), "utf8");
    const committedTypes = await readFile(join(stylesDirectory, "tokens.d.ts"), "utf8");
    execFileSync("df", ["-h", "/"], { cwd: repoRoot, stdio: "inherit" });
    execFileSync("pnpm", ["--dir", "web", "tokens"], { cwd: repoRoot });
    expect(await readFile(join(stylesDirectory, "tokens.css"), "utf8")).toBe(committedCss);
    expect(await readFile(join(stylesDirectory, "tokens.d.ts"), "utf8")).toBe(committedTypes);
  });

  it("oklch_with_hex_fallback", async () => {
    const tokens = await readTokens();
    const css = await readFile(resolve(repoRoot, "web/src/styles/tokens.css"), "utf8");
    expect(css).toContain("@supports not (color: oklch(0 0 0))");

    for (const theme of ["light", "dark"] as const) {
      for (const tokenName of Object.keys(tokens.color[theme])) {
        const property = `--token-color-${tokenName}`;
        expect(css).toMatch(new RegExp(`${property}:\\s*oklch\\(`));
        expect(css.match(new RegExp(`${property}:\\s*#[0-9a-f]{6};`, "gi"))).not.toBeNull();
      }
    }
  });

  it("ds_a11y_02_focus_ring_and_reduced_motion", async () => {
    const css = await readFile(resolve(repoRoot, "web/src/styles/base.css"), "utf8");
    const style = document.createElement("style");
    style.textContent = css;
    document.head.append(style);

    const focusTarget = document.createElement("button");
    focusTarget.textContent = "Focus test";
    document.body.append(focusTarget);
    focusTarget.focus();
    expect(document.activeElement).toBe(focusTarget);

    const rules = Array.from(style.sheet?.cssRules ?? []);
    const focusRule = rules
      .map((rule) => rule as CSSStyleRule)
      .find((rule) => rule.selectorText?.includes(":focus-visible"));
    expect(focusRule?.style.getPropertyValue("outline-width")).toBe("2px");
    expect(focusRule?.style.getPropertyValue("outline-offset")).toBe("2px");

    const reducedMotion = rules
      .filter((rule) => rule.type === CSSRule.MEDIA_RULE)
      .map((rule) => rule as CSSMediaRule)
      .find((rule) => rule.conditionText.includes("prefers-reduced-motion"));
    const reducedMotionRule = Array.from(reducedMotion?.cssRules ?? [])
      .map((rule) => rule as CSSStyleRule)
      .find((rule) => rule.selectorText?.includes("*"));
    expect(reducedMotionRule?.style.getPropertyValue("transform")).toBe("none");
    expect(reducedMotionRule?.style.getPropertyValue("animation")).toBe("none");
  });

  it("fe_13_fonts_self_hosted_with_licences", async () => {
    const dist = resolve(repoRoot, "web/dist");
    const assetDirectory = resolve(dist, "assets");
    const assetFiles = await readdir(assetDirectory);
    const cssFiles = assetFiles.filter((file) => file.endsWith(".css"));
    const document = await readFile(resolve(dist, "index.html"), "utf8");
    const stylesheets = await Promise.all(
      cssFiles.map((file) => readFile(join(assetDirectory, file), "utf8")),
    );
    const fontReferences = `${document}\n${stylesheets.join("\n")}`;
    const fontsDirectory = resolve(dist, "fonts");
    const fontFiles = await readdir(fontsDirectory);
    const licences = await readFile(join(fontsDirectory, "FONT-LICENSES.txt"), "utf8");

    expect(fontReferences).not.toMatch(/url\(["']?https?:\/\//i);
    for (const [family, filename] of [
      ["Fraunces", "fraunces-latin-ext.woff2"],
      ["Inter", "inter-latin-ext.woff2"],
      ["JetBrains Mono", "jetbrains-mono-latin-ext.woff2"],
    ]) {
      expect(fontReferences).toContain(family);
      expect(fontFiles).toContain(filename);
      expect(licences).toContain(family);
      expect(licences).toContain("SIL OPEN FONT LICENSE Version 1.1");
    }
  });
});
